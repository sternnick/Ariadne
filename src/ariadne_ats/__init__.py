"""ariadne_ats — the Ariadne package (renamed from `ats_research` 2026-10-25, D-015).

Honest public surface: everything exported here exists, is importable, and does what its
module docstring says. Nothing is imported "for the API" that is not implemented.

Implemented today:
    textutil    normalize / tokenize / content_words / sentences / ngrams / term_frequencies,
                SECTION_HEADINGS (the heading vocabulary)
    extract     extract() — text, DOCX via stdlib, PDF via an optional backend, typed failures
    layout      analyze() — column/table/band/glyph damage, read from the RAW extraction
    segment     segment() — one Section per heading occurrence, with per-section confidence
    fields      contact block, personal name, role lines (title + employer + span), summary
    evidence    Fact / Ledger / LedgerDelta / build_ledger — the two-hash evidence model
    jd          build_jd() — requirements with must/nice/unknown weights and spans
    lexical     Tfidf (fit / vector / cosine / compare), jaccard, overlap_coefficient
    perturb     four competence-preserving transforms (M-2 substrate)
    bench       scores the package against data/gold/ — field accuracy and perturbation stability

Deliberately NOT here, because they do not exist yet:
    score, ScoreResult, lint, Finding                            -> A2
    propose, Proposal, check_support, SupportReport              -> A3
    HashingEmbedder, OpenAICompatibleEmbedder                     -> A2/A3
    any person-level assessment (forbidden by AGENT_CONTRACT C9, tested by tests/test_no_profiling.py)

The old helper names `bullets_of`, `detect_sections`, `heading_of` and `looks_multicolumn` are gone:
each was deleted in A1 and replaced by `segment.bullets()`, `segment.segment()`, `layout.analyze()`.
Their removal is recorded in docs/00-audit.md A.5 (P3, P4, P5) rather than kept as shims.

Measured, not asserted: `ariadne bench` (or `scripts/bench.py`) reports field accuracy against
`data/gold/` and stability under perturbation; the published numbers live in docs/02 §2.6 and
docs/05 §5.1 and are regenerated by `scripts/bench.py --write`.
"""
